def bitmap(font, s, features=None):
    """render s at the baseline origin: (w, h, x, y, adv, 4bpp rows)"""
    kw = {'anchor': 'ls'}
    if features is not None:
        kw['features'] = features
    x0, y0, x1, y1 = font.getbbox(s, **kw)
    adv = round(font.getlength(s))
    w, h = max(1, x1 - x0), max(1, y1 - y0)
    im = Image.new('L', (w, h), 0)
    ImageDraw.Draw(im).text((-x0, -y0), s, font=font, fill=255, **kw)
    data = bytearray()
    for yy in range(h):
        row = [(im.getpixel((xx, yy)) * 15 + 127) // 255 for xx in range(w)]
        if len(row) % 2:
            row.append(0)
        for i in range(0, len(row), 2):
            data.append(row[i] << 4 | row[i + 1])
    return w, h, x0, y0, adv, data


def emit_font(name, font, chars, extra=None, extra_font=None):
    """chars: string of ASCII; extra: {code: unicode char} rendered with extra_font"""
    glyphs, data, index = [], bytearray(), [255] * 128
    items = [(ord(c), font, c) for c in chars] + [(code, extra_font, u) for code, u in (extra or {}).items()]
    for code, f, c in items:
        w, h, x, y, adv, d = bitmap(f, c)
        index[code] = len(glyphs)
        glyphs.append((w, h, x, y, adv, len(data)))
        data += d
    asc, desc = font.getmetrics()
    out.append(f'static const uint8_t {name}_data[{len(data)}] = {{{",".join(str(b) for b in data)}}};')
    out.append(f'static const glyph_t {name}_glyphs[{len(glyphs)}] = {{' +
               ','.join(f'{{{w},{h},{x},{y},{adv},{o}}}' for w, h, x, y, adv, o in glyphs) + '};')
    out.append(f'static const uint8_t {name}_index[128] = {{{",".join(map(str, index))}}};')
    out.append(f'static const font_t {name} = {{{name}_glyphs, {name}_data, {name}_index, {asc}, {desc}}};')
    out.append('')
    return len(data)


