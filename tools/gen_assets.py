def petal(img, base, length, width, angle, c_tip, c_base, edge):
    """a pointed petal from base (x, y), pointing at angle (0 = up), filled with a gradient"""
    pts = []
    n = 40
    for i in range(n + 1):  # one side, then the other
        t = i / n
        pts.append((t, width * math.sin(math.pi * t ** 0.85) * (1 - t * 0.25)))
    poly = [(t, w) for t, w in pts] + [(t, -w) for t, w in reversed(pts)]
    a = math.radians(angle)
    ca, sa = math.cos(a), math.sin(a)
    P = [(base[0] + (w * ca + t * length * sa), base[1] + (w * sa - t * length * ca)) for t, w in poly]
    mask = Image.new('L', img.size, 0)
    ImageDraw.Draw(mask).polygon(P, fill=255)
    grad = Image.new('RGB', img.size)
    gp = ImageDraw.Draw(grad)
    x0 = min(p[0] for p in P)
    y0, y1 = min(p[1] for p in P), max(p[1] for p in P)
    # gradient along the petal: base colour at the base, tip colour at the tip
    for k in range(48):
        t = k / 47
        c = lerp(c_base, c_tip, t ** 0.8)
        r = length * (1 - t)
        bx, by = base[0] + length * sa * t, base[1] - length * ca * t
        gp.ellipse((bx - width * 1.3, by - width * 1.3, bx + width * 1.3, by + width * 1.3), fill=c)
    img.paste(grad, (0, 0), mask)
    ImageDraw.Draw(img).line(P + [P[0]], fill=edge, width=max(1, S // 2))


